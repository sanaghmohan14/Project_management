def get_default_approval_authority(item_id=None, scope_no=None, category=None, item_no=None, name=None):
    """Return pre-assigned Final Approval Authority (TL, PM, VP, CEO) for any scope item."""
    if item_id:
        clean_id = str(item_id).strip().upper()
        if clean_id in ITEM_ID_APPROVAL_AUTHORITY:
            return ITEM_ID_APPROVAL_AUTHORITY[clean_id]
        parts = clean_id.split('-')
        if len(parts) == 3:
            try:
                s_part = f"S{int(parts[0].replace('S', '')):02d}"
                c_part = parts[1].upper()
                n_part = f"{int(parts[2]):03d}"
                norm_id = f"{s_part}-{c_part}-{n_part}"
                if norm_id in ITEM_ID_APPROVAL_AUTHORITY:
                    return ITEM_ID_APPROVAL_AUTHORITY[norm_id]
            except Exception:
                pass

    if scope_no is not None and category and item_no is not None:
        try:
            s_num = int(scope_no)
            i_num = int(item_no)
            cat_norm = 'Implementation' if 'imp' in str(category).lower() else 'Documentation'
            key = f"{s_num}:{cat_norm}:{i_num}"
            if key in SCOPE_ITEM_APPROVAL_AUTHORITY:
                return SCOPE_ITEM_APPROVAL_AUTHORITY[key]
        except Exception:
            pass

    return 'TL'
